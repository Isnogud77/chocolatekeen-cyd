// assetdump: turn Keen 1 data files into const C arrays for flash.
//
// Usage: assetdump <data dir> <out dir>
//
// Pixel layout is byte-identical to what upstream gfx.c builds at runtime
// (CVort_engine_decompGraphics): one byte per pixel, bits 0-3 = EGA color
// (B,G,R,I), bit 4 = sprite mask. The EXE image is unpacked like upstream
// load_exe_image(). Decompression reuses the upstream (Commander Genius)
// lz.c and Cunlzexe.c.

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "render/gfx.h"
#include "third_party/cgenius/fileio/lz.h"
#include "third_party/cgenius/fileio/compression/Cunlzexe.h"

static const char *dataDir, *outDir;

static void die(const char *msg, const char *arg) {
    fprintf(stderr, "assetdump: %s %s\n", msg, arg ? arg : "");
    exit(1);
}

static FILE *openData(const char *name) {
    char path[1024];
    snprintf(path, sizeof path, "%s/%s", dataDir, name);
    FILE *fp = fopen(path, "rb");
    if (!fp) die("cannot open", path);
    return fp;
}

static uint8_t *readAll(const char *name, uint32_t *len) {
    FILE *fp = openData(name);
    fseek(fp, 0, SEEK_END);
    *len = (uint32_t)ftell(fp);
    fseek(fp, 0, SEEK_SET);
    uint8_t *buf = malloc(*len);
    if (fread(buf, *len, 1, fp) != 1) die("short read", name);
    fclose(fp);
    return buf;
}

static uint16_t rd16(const uint8_t *p) { return p[0] | p[1] << 8; }
static uint32_t rd32(const uint8_t *p) { return rd16(p) | (uint32_t)rd16(p + 2) << 16; }

// De-plane npix pixels starting at src; planes are planeSize apart.
static void deplane(const uint8_t *src, uint32_t planeSize, int planes, uint32_t npix, uint8_t *out) {
    for (uint32_t i = 0; i < npix; i++) {
        uint8_t px = 0;
        for (int p = 0; p < planes; p++)
            if (src[i / 8 + p * planeSize] & (1 << ((i % 8) ^ 7)))
                px |= 1 << p;
        out[i] = px;
    }
}

static FILE *openOut(const char *name) {
    char path[1024];
    snprintf(path, sizeof path, "%s/%s", outDir, name);
    FILE *fp = fopen(path, "w");
    if (!fp) die("cannot write", path);
    fprintf(fp, "// GENERATED by tools/assetdump from Keen 1 data. Do not edit.\n");
    return fp;
}

static void emitBytes(FILE *fp, const char *name, const uint8_t *data, uint32_t len) {
    fprintf(fp, "const uint8_t %s[%u] = {", name, len ? len : 1);
    for (uint32_t i = 0; i < len; i++)
        fprintf(fp, "%s0x%02x,", (i % 16) ? "" : "\n", data[i]);
    fprintf(fp, "\n};\n");
}

static void emitU32s(FILE *fp, const char *name, const uint32_t *v, int n) {
    fprintf(fp, "const uint32_t %s[%d] = {", name, n);
    for (int i = 0; i < n; i++)
        fprintf(fp, "%s%u,", (i % 8) ? "" : "\n", v[i]);
    fprintf(fp, "\n};\n");
}

// Default EGA palette, for the PPM previews only.
static void egaRgb(uint8_t idx, uint8_t rgb[3]) {
    uint8_t i = (idx & 8) ? 0x55 : 0;
    rgb[0] = ((idx & 4) ? 0xAA : 0) + i;
    rgb[1] = ((idx & 2) ? 0xAA : 0) + i;
    rgb[2] = ((idx & 1) ? 0xAA : 0) + i;
    if (idx == 6) rgb[1] = 0x55; // brown
}

static void writePpm(const char *name, const uint8_t *pix, int w, int h) {
    char path[1024];
    snprintf(path, sizeof path, "%s/%s", outDir, name);
    FILE *fp = fopen(path, "wb");
    if (!fp) die("cannot write", path);
    fprintf(fp, "P6\n%d %d\n255\n", w, h);
    for (int i = 0; i < w * h; i++) {
        uint8_t rgb[3];
        egaRgb(pix[i] & 15, rgb);
        if (pix[i] & 16) rgb[0] = 0xFF, rgb[1] = 0x00, rgb[2] = 0xFF; // mask = magenta
        fwrite(rgb, 3, 1, fp);
    }
    fclose(fp);
}

int main(int argc, char **argv) {
    if (argc != 3) die("usage: assetdump <data dir> <out dir>", NULL);
    dataDir = argv[1];
    outDir = argv[2];

    /* --- EGAHEAD --- */
    uint32_t headLen;
    uint8_t *head = readAll("EGAHEAD.CK1", &headLen);
    EGAHeadGeneralSection_T g;
    const uint8_t *p = head;
    g.latchPlaneSize = rd32(p); p += 4;
    g.sprPlaneSize = rd32(p); p += 4;
    g.imgDataStart = rd32(p); p += 4;
    g.sprDataStart = rd32(p); p += 4;
    g.fontNum = rd16(p); p += 2;  g.fontLoc = rd32(p); p += 4;
    g.unkNum = rd16(p); p += 2;   g.unkLoc = rd32(p); p += 4;
    g.tileNum = rd16(p); p += 2;  g.tileLoc = rd32(p); p += 4;
    g.bmpNum = rd16(p); p += 2;   g.bmpLoc = rd32(p); p += 4;
    g.spriteNum = rd16(p); p += 2; g.spriteLoc = rd32(p); p += 4;
    g.compression = rd16(p);

    EGAHeadUnmasked_T *bmps = calloc(g.bmpNum, sizeof *bmps);
    p = head + g.imgDataStart;
    for (int i = 0; i < g.bmpNum; i++, p += 16) {
        bmps[i].h = rd16(p);
        bmps[i].v = rd16(p + 2);
        bmps[i].loc = rd32(p + 4);
        memcpy(bmps[i].name, p + 8, 8);
    }
    int nSprEntries = 4 * g.spriteNum;
    MaskedSpriteEntry_T *spr = calloc(nSprEntries, sizeof *spr);
    p = head + g.sprDataStart;
    for (int i = 0; i < nSprEntries; i++, p += 32) {
        spr[i].width = rd16(p);       spr[i].height = rd16(p + 2);
        spr[i].loc_offset = rd16(p + 4); spr[i].location = rd16(p + 6);
        spr[i].hitbox_l = rd16(p + 8);  spr[i].hitbox_u = rd16(p + 10);
        spr[i].hitbox_r = rd16(p + 12); spr[i].hitbox_b = rd16(p + 14);
        memcpy(spr[i].name, p + 16, 12);
        spr[i].h_v_off = rd32(p + 28);
    }

    /* --- EGALATCH: bitmaps, font, tiles --- */
    uint8_t *latch = calloc(g.latchPlaneSize, 4);
    FILE *fp = openData("EGALATCH.CK1");
    if (g.compression & 2) lz_decompress(fp, latch);
    else if (fread(latch, g.latchPlaneSize * 4, 1, fp) != 1) die("short read", "EGALATCH");
    fclose(fp);

    uint32_t *bmpOff = calloc(g.bmpNum, sizeof *bmpOff), bmpTotal = 0;
    for (int i = 0; i < g.bmpNum; i++) { bmpOff[i] = bmpTotal; bmpTotal += 8u * bmps[i].h * bmps[i].v; }
    uint8_t *bmpData = malloc(bmpTotal);
    for (int i = 0; i < g.bmpNum; i++)
        deplane(latch + g.bmpLoc + bmps[i].loc, g.latchPlaneSize, 4, 8u * bmps[i].h * bmps[i].v, bmpData + bmpOff[i]);

    uint8_t *fontData = malloc(g.fontNum * 64u);
    deplane(latch + g.fontLoc, g.latchPlaneSize, 4, g.fontNum * 64u, fontData);
    uint8_t *tileData = malloc(g.tileNum * 256u);
    deplane(latch + g.tileLoc, g.latchPlaneSize, 4, g.tileNum * 256u, tileData);

    /* --- EGASPRIT: one copy per sprite, upstream ignores the 3 shift copies --- */
    uint8_t *sprite = calloc(g.sprPlaneSize, 5);
    fp = openData("EGASPRIT.CK1");
    if (g.compression & 1) lz_decompress(fp, sprite);
    else if (fread(sprite, g.sprPlaneSize * 5, 1, fp) != 1) die("short read", "EGASPRIT");
    fclose(fp);

    uint32_t *sprOff = calloc(g.spriteNum, sizeof *sprOff), sprTotal = 0;
    for (int i = 0; i < g.spriteNum; i++) { sprOff[i] = sprTotal; sprTotal += 8u * spr[4 * i].width * spr[4 * i].height; }
    uint8_t *sprData = malloc(sprTotal);
    for (int i = 0; i < g.spriteNum; i++) {
        const MaskedSpriteEntry_T *e = &spr[4 * i];
        deplane(sprite + g.spriteLoc + e->loc_offset + 16u * e->location, g.sprPlaneSize, 5,
                8u * e->width * e->height, sprData + sprOff[i]);
    }

    /* --- write keen1_gfx.c --- */
    FILE *out = openOut("keen1_gfx.c");
    fprintf(out, "#include \"keen1_assets.h\"\n\n");
    fprintf(out, "const EGAHeadGeneralSection_T keen1_egaHead = {%u,%u,%u,%u, %u,%u, %u,%u, %u,%u, %u,%u, %u,%u, %u};\n",
            g.latchPlaneSize, g.sprPlaneSize, g.imgDataStart, g.sprDataStart, g.fontNum, g.fontLoc,
            g.unkNum, g.unkLoc, g.tileNum, g.tileLoc, g.bmpNum, g.bmpLoc, g.spriteNum, g.spriteLoc, g.compression);
    fprintf(out, "const EGAHeadUnmasked_T keen1_bmpHeads[%d] = {\n", g.bmpNum);
    for (int i = 0; i < g.bmpNum; i++)
        fprintf(out, " {%u,%u,%u,{%u,%u,%u,%u,%u,%u,%u,%u}},\n", bmps[i].h, bmps[i].v, bmps[i].loc,
                (uint8_t)bmps[i].name[0], (uint8_t)bmps[i].name[1], (uint8_t)bmps[i].name[2], (uint8_t)bmps[i].name[3],
                (uint8_t)bmps[i].name[4], (uint8_t)bmps[i].name[5], (uint8_t)bmps[i].name[6], (uint8_t)bmps[i].name[7]);
    fprintf(out, "};\nconst MaskedSpriteEntry_T keen1_spriteEntries[%d] = {\n", nSprEntries);
    for (int i = 0; i < nSprEntries; i++) {
        fprintf(out, " {%u,%u,%u,%u,%u,%u,%u,%u,{", spr[i].width, spr[i].height, spr[i].loc_offset, spr[i].location,
                spr[i].hitbox_l, spr[i].hitbox_u, spr[i].hitbox_r, spr[i].hitbox_b);
        for (int c = 0; c < 12; c++) fprintf(out, "%u,", (uint8_t)spr[i].name[c]);
        fprintf(out, "},%u},\n", spr[i].h_v_off);
    }
    fprintf(out, "};\n");
    emitBytes(out, "keen1_tileData", tileData, g.tileNum * 256u);
    emitBytes(out, "keen1_fontData", fontData, g.fontNum * 64u);
    emitBytes(out, "keen1_bmpData", bmpData, bmpTotal);
    emitU32s(out, "keen1_bmpOffsets", bmpOff, g.bmpNum);
    emitBytes(out, "keen1_spriteData", sprData, sprTotal);
    emitU32s(out, "keen1_spriteOffsets", sprOff, g.spriteNum);
    fprintf(out, "const uint32_t keen1_spriteDataSize = %u;\n", sprTotal);
    fclose(out);

    /* --- KEEN1.EXE, unpacked like upstream load_exe_image() --- */
    uint32_t exeLen;
    uint8_t *exe = readAll("KEEN1.EXE", &exeLen), *unpacked = NULL, *image;
    uint32_t imageLen;
    if (Cunlzexe_decompress(exe, &unpacked)) {
        uint32_t hdr = (uint32_t)Cunlzexe_getHeaderSize();
        imageLen = (uint32_t)Cunlzexe_getUncompressedExeSize() - hdr;
        image = unpacked + hdr;
    } else {
        uint32_t hdr = 16u * (exe[8] + 16u * exe[9]);
        imageLen = exeLen - hdr;
        image = exe + hdr;
    }
    out = openOut("keen1_exe.c");
    fprintf(out, "#include \"keen1_assets.h\"\n\n");
    emitBytes(out, "keen1_exeImage", image, imageLen);
    fprintf(out, "const uint32_t keen1_exeImageSize = %u;\n", imageLen);
    fclose(out);

    /* --- raw files read through the fopen shim --- */
    static const char *rawFiles[] = {"LEVEL01.CK1", "LEVEL14.CK1"}; // 14: large level, used by tests
    const int nRaw = sizeof rawFiles / sizeof rawFiles[0];
    out = openOut("keen1_files.c");
    fprintf(out, "#include \"keen1_assets.h\"\n\n");
    for (int i = 0; i < nRaw; i++) {
        uint32_t len;
        uint8_t *d = readAll(rawFiles[i], &len);
        char sym[64];
        snprintf(sym, sizeof sym, "file%d", i);
        fprintf(out, "static ");
        emitBytes(out, sym, d, len);
        free(d);
    }
    fprintf(out, "const AssetFile_T keen1_files[%d] = {\n", nRaw);
    for (int i = 0; i < nRaw; i++) {
        uint32_t len;
        free(readAll(rawFiles[i], &len));
        fprintf(out, " {\"%s\", file%d, %u},\n", rawFiles[i], i, len);
    }
    fprintf(out, "};\nconst int keen1_filesCount = %d;\n", nRaw);
    fclose(out);

    /* --- previews: tiles 16 per row; sprites stacked, 64 px wide cells --- */
    int rows = (g.tileNum + 15) / 16;
    uint8_t *sheet = calloc(256u * rows * 16, 1);
    for (int t = 0; t < g.tileNum; t++)
        for (int y = 0; y < 16; y++)
            memcpy(sheet + ((t / 16) * 16 + y) * 256 + (t % 16) * 16, tileData + t * 256 + y * 16, 16);
    writePpm("tiles.ppm", sheet, 256, rows * 16);
    free(sheet);

    int sh = 0;
    for (int i = 0; i < g.spriteNum; i++) sh += spr[4 * i].height + 2;
    sheet = calloc(64u * sh, 1);
    int y0 = 0;
    for (int i = 0; i < g.spriteNum; i++) {
        const MaskedSpriteEntry_T *e = &spr[4 * i];
        int w = 8 * e->width;
        for (int y = 0; y < e->height; y++)
            for (int x = 0; x < w && x < 64; x++)
                sheet[(y0 + y) * 64 + x] = sprData[sprOff[i] + y * w + x];
        y0 += e->height + 2;
    }
    writePpm("sprites.ppm", sheet, 64, sh);

    printf("tiles %u, sprites %u (%u bytes), bitmaps %u (%u bytes), fonts %u, exe image %u bytes\n",
           g.tileNum, g.spriteNum, sprTotal, g.bmpNum, bmpTotal, g.fontNum, imageLen);
    return 0;
}
